package training;

public class Operaters {

	public static void main(String[] args) {
		System.out.println("Aithemtic Operation"); 
		System.out.println(5+3*2);
		System.out.println(4+5*2-3);
		System.out.println(5+2*3-4/2);
		
		System.out.println("Relational operation");
		System.out.println(3>2);
		System.out.println(4==2);
		System.out.println(3!=2);
		System.out.println(23<3);
		System.out.println(3<=3);
		
		System.out.println("Logical Operations");
		System.out.println(5<10&&3==3);
		System.out.println(!(5>10));
		System.out.println(55==3);
		System.out.println(3!=2);
		System.out.println(1>2||3==3);
		System.out.println(3<4&&4==3);
		

	}

}
